/// One catalog row: a single quantization of a single transcribe.cpp variant.
#[derive(Debug, Clone, Copy)]
pub struct TranscribeModel {
    /// Stable identifier stored in `transcript_settings.model`.
    pub name: &'static str,
    /// Display family, e.g. "Whisper". The picker groups by this.
    pub family: &'static str,
    pub hf_repo: &'static str,
    pub filename: &'static str,
    pub size_mb: u32,
    pub accuracy: &'static str,
    pub speed: &'static str,
    /// Whether this variant can drive `Session::stream()`.
    ///
    /// Display only — it decides the "live-capable" tag in the picker before the
    /// GGUF exists on disk. The decode path is chosen from
    /// `Capabilities::supports_streaming` on the loaded model, which is read
    /// from GGUF metadata and cannot drift.
    pub streaming: bool,
    /// Human-readable coverage for the picker before the model is downloaded.
    /// Once loaded, `Capabilities::languages` is authoritative.
    pub languages: &'static str,
    pub description: &'static str,
}

