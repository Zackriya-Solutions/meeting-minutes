/// Set once the example has been seeded. Its presence — not the meeting's — is what stops
/// re-seeding, so a user who deletes the example keeps it deleted.
const MARKER_KEY: &str = "demo.meeting.seeded";

/// Fixed id: the frontend opens this meeting right after onboarding, and a stable id keeps
/// that link valid without a round-trip to find it.
