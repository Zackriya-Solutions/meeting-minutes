//! The example meeting a fresh install starts with.
//!
//! Until a first real recording exists, every screen in the app is empty: there is no
//! transcript to read, no summary to judge, and no analytical report to open. So a fresh
//! database gets one synthetic meeting — a short fictional planning call — with the same
//! artifacts a real recording would have: a diarized transcript on a real timeline, a
//! completed summary, and a completed analytics report (row + rendered HTML).
//!
//! Nothing here calls an LLM. The conversation and the stage artifacts are authored
//! constants; the two things that must not drift from real runs — `Dynamics` and the
//! meeting score — are computed by the pipeline's own deterministic code over the seeded
//! transcript, and the HTML comes from the pipeline's own renderer.
//!
//! Seeding happens once. The marker in `app_settings_kv` is written after a successful
//! seed, so deleting the example is permanent: it never comes back on the next launch.

