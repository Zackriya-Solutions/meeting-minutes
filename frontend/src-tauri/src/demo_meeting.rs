#[cfg(test)]
mod tests {
    use super::*;
    use sqlx::sqlite::SqlitePoolOptions;

    async fn migrated_pool() -> SqlitePool {
        let pool = SqlitePoolOptions::new()
            .max_connections(1)
            .connect("sqlite::memory:")
            .await
            .unwrap();
        sqlx::migrate!("./migrations").run(&pool).await.unwrap();
        pool
    }

    /// The example is only useful if the app can read it back. This walks the same path the
    /// meeting screen takes — transcript segments, the deterministic timeline, then
    /// `sections::build` over the stored snapshot — so a wrong column, a NOT NULL violation,
    /// or an artifact shape the reader rejects fails here rather than on a user's first launch.
    #[tokio::test]
    async fn the_example_is_readable_by_the_meeting_screen() {
        use crate::database::repositories::speaker::SpeakersRepository;
        use crate::report::sections::{self, TranscriptTimeline};

        let pool = migrated_pool().await;
        seed_meeting(&pool).await.expect("example seeds");

        let segments = SpeakersRepository::meeting_transcript_segments(&pool, DEMO_MEETING_ID)
            .await
            .expect("transcript reads back");
        assert_eq!(segments.len(), REPLIES.len());
        assert!(
            segments.iter().all(|s| s.display_name.is_some()),
            "every reply must carry a speaker name, not «Спикер 1»"
        );

        let summary = sqlx::query_scalar::<_, String>(
            "SELECT result FROM summary_processes WHERE meeting_id = ? AND status = 'completed'",
        )
        .bind(DEMO_MEETING_ID)
        .fetch_one(&pool)
        .await
        .expect("summary is stored as a completed process");
        assert!(
            summary.contains("markdown"),
            "summary must be in the markdown format the UI reads"
        );

        let (artifacts, html) = build_report(&pool, "06.08.2026")
            .await
            .expect("report builds");
        assert!(
            html.contains("Компас"),
            "the rendered report mentions the meeting"
        );

        let (dyn_segments, _, texts) = crate::report::pipeline::build_segment_views(&segments);
        let timed = dynamics::timeline(&dyn_segments);
        let live = Dynamics::from_timed(&dyn_segments, &timed);
        let built = sections::build(
            "report-example",
            Some("2026-08-06 10:00:00".to_string()),
            &artifacts,
            Some(&TranscriptTimeline {
                timed: &timed,
                texts: &texts,
                dynamics: &live,
            }),
        )
        .expect("the snapshot parses");

        let score = built.score.expect("the score section is present");
        assert!(score.total > 0 && !score.verdict.is_empty());
        assert_eq!(built.agenda.len(), 3, "all three agenda items are shown");
        assert_eq!(built.numbers.len(), 4);
        assert_eq!(built.roles.len(), 3);
        assert!(!built.what_hindered.is_empty());

        // Provenance: `segment_count` matches, so every moment link must resolve. A silently
        // dropped link is exactly the failure this snapshot exists to avoid.
        assert!(
            built.agenda.iter().all(|item| item.at_seconds.is_some()),
            "agenda moments must resolve against the seeded transcript"
        );
        assert!(built.numbers.iter().all(|row| row.at_seconds.is_some()));

        let dynamics_section = built.dynamics.expect("dynamics are present");
        assert_eq!(dynamics_section.speakers.len(), SPEAKER_NAMES.len());
        assert_eq!(dynamics_section.decisions_count, Some(3));
        assert_eq!(dynamics_section.commitments_count, Some(4));

        let timeline = built.timeline.expect("the feed is present");
        assert_eq!(timeline.turns.len(), REPLIES.len());
        assert!(!timeline.topics.is_empty());
        assert!(
            timeline.markers.len() >= 7,
            "decisions, commitments and the disagreement all mark the feed"
        );
    }

    #[test]
    fn every_referenced_segment_exists() {
        let last = (REPLIES.len() - 1) as i64;
        let mut segs: Vec<i64> = Vec::new();
        segs.extend(topics().agenda.iter().map(|a| a.seg));
        segs.extend(decisions().decisions.iter().map(|d| d.seg));
        segs.extend(commitments().commitments.iter().map(|c| c.seg));
        segs.extend(threads_risks().open_threads.iter().map(|t| t.seg));
        segs.extend(threads_risks().risks.iter().map(|r| r.seg));
        segs.extend(numbers().numbers.iter().map(|n| n.seg));
        segs.extend(roles().roles.iter().map(|r| r.seg));
        segs.extend(insights().insights.iter().flat_map(|i| i.segs.clone()));
        segs.extend(
            disagreements_concepts()
                .disagreements
                .iter()
                .flat_map(|d| d.positions.iter().map(|p| p.seg)),
        );

        for seg in segs {
            assert!(
                (0..=last).contains(&seg),
                "artifact points at reply {seg}, which the example transcript does not have"
            );
        }
    }

    #[test]
    fn replies_are_ordered_and_attributed() {
        let mut previous = -1.0_f64;
        for Reply(at, speaker, text) in REPLIES {
            assert!(
                *at > previous,
                "reply starts must increase: {at} after {previous}"
            );
            assert!(
                *speaker < SPEAKER_NAMES.len(),
                "unknown speaker index {speaker}"
            );
            assert!(!text.trim().is_empty(), "empty reply at {at}");
            previous = *at;
        }
    }

    /// The score is what the meeting screen shows first, so the example must land in a
    /// believable middle: good enough to look real, imperfect enough to be worth reading.
    #[test]
    fn example_score_is_plausible() {
        let topics = topics();
        let commitments = commitments();
        let score = compute_score(
            &topics.agenda,
            &commitments.commitments,
            threads_risks().open_threads.len(),
        );
        assert!(
            (55..=90).contains(&score.total),
            "example score {} is outside the believable range",
            score.total
        );
    }
}
