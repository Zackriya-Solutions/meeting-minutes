fn already_seeded(pool: &SqlitePool) -> impl std::future::Future<Output = bool> + '_ {
    async move {
        sqlx::query_scalar::<_, String>("SELECT value FROM app_settings_kv WHERE key = ? LIMIT 1")
            .bind(MARKER_KEY)
            .fetch_optional(pool)
            .await
            .ok()
            .flatten()
            .is_some()
    }
}

/// Insert the example meeting, its transcript, summary and analytics report.
///
/// Returns the meeting id when something was seeded, `None` when the example already
/// exists (or was deliberately deleted). A failure is logged and swallowed by callers: the
/// example is a convenience, never a precondition for using the app.
pub async fn seed<R: Runtime>(
    app: &AppHandle<R>,
    pool: &SqlitePool,
) -> Result<Option<String>, String> {
    if already_seeded(pool).await {
        return Ok(None);
    }

    let date_str = seed_meeting(pool).await?;

    if let Err(error) = seed_report(app, pool, &date_str).await {
        // The transcript and the summary are already in place; a meeting without the
        // analytics section is still a useful example.
        log::warn!("[demo] example report not created: {error}");
    }

    sqlx::query(
        "INSERT OR REPLACE INTO app_settings_kv (key, value, updated_at) \
         VALUES (?, 'true', datetime('now'))",
    )
    .bind(MARKER_KEY)
    .execute(pool)
    .await
    .map_err(|e| format!("не удалось отметить пример как созданный: {e}"))?;

    log::info!("[demo] seeded the example meeting {DEMO_MEETING_ID}");
    Ok(Some(DEMO_MEETING_ID.to_string()))
}

/// The database half: meeting, speakers, transcript, summary. Returns the meeting's date for
/// the report header. Separate from [`seed`] so it can be tested against a migrated schema
/// without a Tauri app handle.
async fn seed_meeting(pool: &SqlitePool) -> Result<String, String> {
    let now = chrono::Utc::now();
    let started = now - chrono::Duration::minutes(20);

    let mut tx = pool
        .begin()
        .await
        .map_err(|e| format!("не удалось открыть транзакцию для примера встречи: {e}"))?;

    sqlx::query(
        "INSERT OR REPLACE INTO meetings (id, title, created_at, updated_at) VALUES (?, ?, ?, ?)",
    )
    .bind(DEMO_MEETING_ID)
    .bind(TITLE)
    .bind(started)
    .bind(now)
    .execute(&mut *tx)
    .await
    .map_err(|e| format!("не удалось создать пример встречи: {e}"))?;

    // Confirmed speakers: the example shows named people, not "Спикер 1". No voice
    // embedding is stored — these names must never take part in matching a real voice.
    let mut speaker_ids = Vec::with_capacity(SPEAKER_NAMES.len());
    for name in SPEAKER_NAMES {
        let result = sqlx::query(
            "INSERT INTO speakers (display_name, is_confirmed, created_at) \
             VALUES (?, 1, datetime('now'))",
        )
        .bind(name)
        .execute(&mut *tx)
        .await
        .map_err(|e| format!("не удалось создать участника примера: {e}"))?;
        speaker_ids.push(result.last_insert_rowid());
    }

    for (index, Reply(at, speaker, text)) in REPLIES.iter().enumerate() {
        // The spoken end is what the pipeline estimates from the text, bounded by the next
        // reply; storing the same bound keeps per-speaker speech time honest in the UI.
        let next_start = REPLIES.get(index + 1).map(|Reply(next, _, _)| *next);
        let estimated_end = at + (text.split_whitespace().count() as f64 / 2.5).max(0.5);
        let end = next_start.map_or(estimated_end, |next| estimated_end.min(next));

        sqlx::query(
            "INSERT INTO transcripts \
             (id, meeting_id, transcript, timestamp, audio_start_time, audio_end_time, duration, speaker_id) \
             VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
        )
        .bind(format!("transcript-example-{index:03}"))
        .bind(DEMO_MEETING_ID)
        .bind(*text)
        .bind((started + chrono::Duration::milliseconds((at * 1000.0) as i64)).to_rfc3339())
        .bind(*at)
        .bind(end)
        .bind(end - at)
        .bind(speaker_ids[*speaker])
        .execute(&mut *tx)
        .await
        .map_err(|e| format!("не удалось сохранить реплику примера: {e}"))?;
    }

    sqlx::query(
        "INSERT OR REPLACE INTO summary_processes \
         (meeting_id, status, created_at, updated_at, start_time, end_time, result, chunk_count, processing_time) \
         VALUES (?, 'completed', ?, ?, ?, ?, ?, 1, 0)",
    )
    .bind(DEMO_MEETING_ID)
    .bind(now)
    .bind(now)
    .bind(now)
    .bind(now)
    .bind(json!({ "markdown": SUMMARY_MARKDOWN }).to_string())
    .execute(&mut *tx)
    .await
    .map_err(|e| format!("не удалось сохранить итоги примера: {e}"))?;

    tx.commit()
        .await
        .map_err(|e| format!("не удалось сохранить пример встречи: {e}"))?;

    Ok(started.format("%d.%m.%Y").to_string())
}

/// Build the analytics report for the example: authored stage artifacts, deterministic
/// dynamics and score, and the real HTML renderer. Returns the artifacts snapshot the meeting
/// screen reads and the rendered HTML.
async fn build_report(pool: &SqlitePool, date_str: &str) -> Result<(String, String), String> {
    use crate::database::repositories::speaker::SpeakersRepository;

    let segments = SpeakersRepository::meeting_transcript_segments(pool, DEMO_MEETING_ID)
        .await
        .map_err(|e| format!("не удалось прочитать расшифровку примера: {e}"))?;
    let (dyn_segments, seg_labels, seg_texts) =
        crate::report::pipeline::build_segment_views(&segments);
    let timed = dynamics::timeline(&dyn_segments);
    let metrics = Dynamics::from_timed(&dyn_segments, &timed);

    let classification = classification();
    let topics = topics();
    let decisions = decisions();
    let commitments = commitments();
    let threads_risks = threads_risks();
    let disagreements = disagreements_concepts();
    let numbers = numbers();
    let roles = roles();
    let insights = insights();
    let score = compute_score(
        &topics.agenda,
        &commitments.commitments,
        threads_risks.open_threads.len(),
    );

    let html = render_report(&RenderInput {
        meeting_title: TITLE,
        date_str,
        model: REPORT_MODEL,
        generation_secs: 0.0,
        total_stages: crate::database::repositories::analytics_report::TOTAL_STAGES,
        dynamics: &metrics,
        timed: &timed,
        seg_labels: &seg_labels,
        seg_texts: &seg_texts,
        classification: Some(&classification),
        topics: Some(&topics),
        decisions: Some(&decisions),
        commitments: Some(&commitments),
        threads_risks: Some(&threads_risks),
        disagreements_concepts: Some(&disagreements),
        numbers: Some(&numbers),
        roles: Some(&roles),
        insights: Some(&insights),
        score: &score,
        clarify_questions: &[],
        clarify_answers: &[],
    });

    let artifacts = json!({
        "segment_count": seg_texts.len(),
        "dynamics": metrics,
        "score": score,
        "classification": classification,
        "clarify_questions": [],
        "clarify_answers": [],
        "topics": topics,
        "decisions": decisions,
        "commitments": commitments,
        "threads_risks": threads_risks,
        "disagreements_concepts": disagreements,
        "numbers": numbers,
        "roles": roles,
        "insights": insights,
        "failed_stages": [],
    })
    .to_string();

    Ok((artifacts, html))
}

/// Persist the example's report: write the HTML the «Открыть отчёт» action opens, then record
/// a completed run pointing at it.
async fn seed_report<R: Runtime>(
    app: &AppHandle<R>,
    pool: &SqlitePool,
    date_str: &str,
) -> Result<(), String> {
    use crate::database::repositories::analytics_report::AnalyticsReportsRepository;

    let (artifacts, html) = build_report(pool, date_str).await?;
    let html_path = crate::report::pipeline::write_html(app, DEMO_MEETING_ID, None, &html)?;

    let report_id = format!("report-example-{DEMO_MEETING_ID}");
    AnalyticsReportsRepository::insert(pool, &report_id, DEMO_MEETING_ID, REPORT_MODEL)
        .await
        .map_err(|e| format!("не удалось создать строку отчёта примера: {e}"))?;
    AnalyticsReportsRepository::mark_completed(pool, &report_id, &html_path, &artifacts)
        .await
        .map_err(|e| format!("не удалось завершить отчёт примера: {e}"))?;

    Ok(())
}

